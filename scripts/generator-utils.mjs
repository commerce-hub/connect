import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

export const workspaceRoot = path.resolve(__dirname, '..');
export const generatedMarkerFile = '.commercehub-generator.json';

export function parseArgs(argv) {
  const options = {
    force: false,
  };

  for (const argument of argv) {
    if (argument === '--force') {
      options.force = true;
      continue;
    }

    if (!argument.startsWith('--')) {
      continue;
    }

    const [rawKey, ...rawValueParts] = argument.slice(2).split('=');
    const key = rawKey.trim();
    const value = rawValueParts.join('=').trim();
    options[key] = value || true;
  }

  return options;
}

export function normalizeProjectName(value, fallback) {
  const candidate = `${value ?? fallback ?? ''}`.trim();

  if (!candidate) {
    throw new Error('A project name is required.');
  }

  if (!/^[a-z0-9][a-z0-9-]*$/.test(candidate)) {
    throw new Error(
      `Invalid project name "${candidate}". Use lowercase letters, numbers, and dashes only.`,
    );
  }

  return candidate;
}

export function projectDir(projectName) {
  return path.join(workspaceRoot, 'projects', projectName);
}

export function workspaceRelative(absolutePath) {
  return path.relative(workspaceRoot, absolutePath) || '.';
}

export async function pathExists(targetPath) {
  try {
    await fs.access(targetPath);
    return true;
  } catch {
    return false;
  }
}

export async function readText(targetPath) {
  return fs.readFile(targetPath, 'utf8');
}

export async function writeText(targetPath, content) {
  await fs.mkdir(path.dirname(targetPath), { recursive: true });
  await fs.writeFile(targetPath, content, 'utf8');
}

export async function copyIfExists(sourcePath, destinationPath) {
  if (!(await pathExists(sourcePath))) {
    return false;
  }

  await fs.mkdir(path.dirname(destinationPath), { recursive: true });
  await fs.copyFile(sourcePath, destinationPath);
  return true;
}

export async function prepareGeneratedProject(targetDir, metadata, options = {}) {
  const { force = false } = options;
  const markerPath = path.join(targetDir, generatedMarkerFile);

  if (await pathExists(targetDir)) {
    if (!(await pathExists(markerPath))) {
      throw new Error(
        `Refusing to overwrite ${workspaceRelative(targetDir)} because it was not generated by these scripts.`,
      );
    }

    if (!force) {
      throw new Error(
        `${workspaceRelative(targetDir)} already exists. Re-run with --force to regenerate it.`,
      );
    }

    await fs.rm(targetDir, { recursive: true, force: true });
  }

  await fs.mkdir(targetDir, { recursive: true });
  await writeText(
    markerPath,
    `${JSON.stringify(
      {
        ...metadata,
        generatedAt: new Date().toISOString(),
      },
      null,
      2,
    )}\n`,
  );
}

export function withTrailingNewline(content) {
  return content.endsWith('\n') ? content : `${content}\n`;
}
